// Generator for the on-demand uptime probe (a Netlify Functions v2 handler).
//
// The CLI emits this into `<bundle>/netlify/functions/uptime.mjs` with the
// fleet's targets baked in. The page calls it AT MOST once per 6 hours (the
// client-side localStorage gate in `uptime-client.js`), and the response also
// carries a 6h cache hint — so serverless invocations stay bounded no matter
// how often the page is viewed. See test/uptime-function.test.js.

// Pure probe: any HTTP response (including a gated 401/403) means the origin
// answered → "live"; a network error or timeout → "down". Exported so it can be
// unit-tested, AND embedded verbatim (via .toString()) into the generated
// function so the tested code is the shipped code — no drift.
export async function probeReachability(url, fetchImpl, timeoutMs) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetchImpl(url, {
      method: "GET",
      // SSRF-safety: do NOT follow redirects. A 3xx already proves the origin
      // answered (→ "live"); following could chase a compromised fleet site's
      // Location into an internal / cloud-metadata URL from the Lambda.
      redirect: "manual",
      signal: controller.signal,
      headers: { "user-agent": "filecap-uptime/1.0" },
    });
    return res ? "live" : "down";
  } catch {
    return "down";
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Build the source of the Netlify v2 uptime function with `targets` baked in.
 * @param {Array<{key:string,url:string}>} targets
 * @param {{ttlSeconds?:number, timeoutMs?:number}} [opts]
 * @returns {string} the .mjs source
 */
export function generateUptimeFunction(targets, { ttlSeconds = 21600, timeoutMs = 8000 } = {}) {
  return `// Auto-generated by filecap web-rollup — DO NOT EDIT.
// On-demand uptime probe (Netlify Functions v2). Checks each fleet site
// server-side (no CORS) and returns { checkedAtMs, sites: { <key>: "live"|"down" } }.
// The page polls this at most once per 6 hours (client localStorage gate), and
// the response carries a ${ttlSeconds}s cache hint, so invocations stay bounded.
const TARGETS = ${JSON.stringify(targets)};
const TIMEOUT_MS = ${timeoutMs};

${probeReachability.toString()}

export default async function uptime(req) {
  // Only GET is probed (and cacheable) — blocks method-based cache-busting abuse.
  if (req && req.method && req.method !== "GET") {
    return new Response("Method Not Allowed", { status: 405 });
  }
  const entries = await Promise.all(
    TARGETS.map(async (t) => [t.key, await probeReachability(t.url, fetch, TIMEOUT_MS)]),
  );
  return new Response(
    JSON.stringify({ checkedAtMs: Date.now(), sites: Object.fromEntries(entries) }),
    {
      status: 200,
      headers: {
        "content-type": "application/json",
        // Browser cache + Netlify DURABLE edge cache. Repeated requests (even a
        // hammered or unauthenticated caller) are served from the edge cache, so
        // the function — and its outbound probes — actually RUN at most ~once per
        // cache window. This caps serverless invocations regardless of request
        // volume, so the endpoint can't be abused to run up the bill.
        "cache-control": "public, max-age=${ttlSeconds}",
        "netlify-cdn-cache-control": "public, durable, s-maxage=${ttlSeconds}",
      },
    },
  );
}
`;
}
